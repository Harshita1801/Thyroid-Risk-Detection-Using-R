# Define the logistic regression function for multiclass classification
log_classifier <- function(X_train, X_test, y_train, y_test) {
  train_data <- data.frame(X_train, y = y_train)
  log_model <- multinom(y ~ ., data = train_data)
  log_pred <- predict(log_model, newdata = data.frame(X_test))
  cm <- confusionMatrix(log_pred, as.factor(y_test))
  acc <- cm$overall['Accuracy']
  train_score <- mean(predict(log_model, newdata = train_data) == y_train)
  test_score <- mean(log_pred == y_test)
  return(list(
    Accuracy_Score = acc,
    Train_Score = train_score,
    Test_Score = test_score,
    Confusion_Matrix = cm$table
  ))
}
