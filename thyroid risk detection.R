# Define model_type method for randomForest
model_type.randomForest <- function(x, ...) {
if (x$type == "classification") {
     return("classification")
   }
   else if (x$type == "regression") {
     return("regression")
   }
   else {
     return("classification")
   }
 }

 # Define predict_model method for randomForest
 predict_model.randomForest <- function(x, newdata, type = "raw", ...) {
   pred <- predict(x, newdata = newdata, type = "prob")
   if (type == "prob") {
     return(as.data.frame(pred))
   }
   else if (type == "raw") {
     return(predict(x, newdata = newdata, type = "response"))
   }
 }

